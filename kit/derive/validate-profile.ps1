<#
.SYNOPSIS
  Validate .harness/project.json: schema, id uniqueness, dependency resolution, cycles,
  duplicate file ownership, impossible verifies, and baseline freshness.

.DESCRIPTION
  project.json is the foundation of the whole harness — status, trigger, and
  finish-step all read it. A typo like "generate" instead of "generates" makes
  status silently compute the wrong answer, with no error anywhere. This script
  turns that into a loud failure.

  Checks:
    FAIL  unknown stage field (with a did-you-mean suggestion)
    FAIL  missing required field (id / generates)
    FAIL  duplicate stage id
    FAIL  id not matching N.N or N.N.N
    FAIL  requires references an unknown stage
    FAIL  dependency cycle
    FAIL  the same file is generated by two different stages
    FAIL  generates contains an absolute path
    WARN  verify is a command that cannot fail (would never count as evidence)
    WARN  stage declares no verify
    WARN  local.json baseline differs from current project.json digest
    WARN  project.json has no risk_policy

  Exit codes:
    0  no FAIL (warnings allowed)
    1  at least one FAIL
    2  project.json missing or unparsable

.PARAMETER SyncBaseline
  Rewrite local.json's project_sha256 to the current digest (after you reviewed
  the change). Without this, the baseline warning is informational only.

.EXAMPLE
  pwsh -File validate-profile.ps1
  pwsh -File validate-profile.ps1 -SyncBaseline
#>
[CmdletBinding()]
param(
    [string] $Root = $(if ($PSScriptRoot) { Split-Path (Split-Path $PSScriptRoot -Parent) -Parent } else { (Get-Location).Path }),
    [switch] $Json,
    [switch] $Quiet,
    [switch] $SyncBaseline,

    # Accept a reviewed contract change in one step: verify the profile, move the
    # baseline, and record a signed `contract_change`. Without this, acknowledging
    # a change meant computing two digests by hand and calling append-event
    # directly - which pushed ledger maintenance onto the human and put a row in
    # events.jsonl whose authorship was nobody's job.
    [string] $Accept = ''
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '_common.ps1')

$projPath  = Join-Path $Root '.harness\project.json'
$localPath = Join-Path $Root '.harness\local.json'

function P { param($o, [string]$n) if ($null -eq $o) { return $null }; $p = $o.PSObject.Properties[$n]; if ($null -eq $p) { return $null }; return $p.Value }

$fails = [System.Collections.Generic.List[object]]::new()
$warns = [System.Collections.Generic.List[object]]::new()

function Add-Fail { param([string]$Where, [string]$Msg) $fails.Add([pscustomobject]@{ where = $Where; msg = $Msg }) }
function Add-Warn { param([string]$Where, [string]$Msg) $warns.Add([pscustomobject]@{ where = $Where; msg = $Msg }) }

# ---------------------------------------------------------------- load
if (-not (Test-Path -LiteralPath $projPath -PathType Leaf)) {
    if ($Json) { [pscustomobject]@{ ok = $false; error = 'project_missing'; path = $projPath } | ConvertTo-Json -Depth 5 }
    elseif (-not $Quiet) { Write-Host "[FAIL] project.json not found: $projPath" -ForegroundColor Red }
    exit 2
}
try { $profile = Get-Content -LiteralPath $projPath -Raw -Encoding UTF8 | ConvertFrom-Json }
catch {
    if ($Json) { [pscustomobject]@{ ok = $false; error = 'project_unparsable'; detail = $_.Exception.Message } | ConvertTo-Json -Depth 5 }
    elseif (-not $Quiet) { Write-Host "[FAIL] project.json is not valid JSON: $($_.Exception.Message)" -ForegroundColor Red }
    exit 2
}

# ---------------------------------------------------------------- levenshtein (for did-you-mean)
function Get-EditDistance {
    param([string]$A, [string]$B)
    $a = $A.ToLower(); $b = $B.ToLower()
    $n = $a.Length; $m = $b.Length
    $d = New-Object 'int[,]' ($n + 1), ($m + 1)
    for ($i = 0; $i -le $n; $i++) { $d[$i, 0] = $i }
    for ($j = 0; $j -le $m; $j++) { $d[0, $j] = $j }
    for ($i = 1; $i -le $n; $i++) {
        for ($j = 1; $j -le $m; $j++) {
            $cost = if ($a[$i - 1] -eq $b[$j - 1]) { 0 } else { 1 }
            $del = $d[($i - 1), $j] + 1
            $ins = $d[$i, ($j - 1)] + 1
            $sub = $d[($i - 1), ($j - 1)] + $cost
            $d[$i, $j] = [Math]::Min([Math]::Min($del, $ins), $sub)
        }
    }
    return $d[$n, $m]
}

# ---------------------------------------------------------------- trivial verify detection
function Test-TrivialVerify {
    param([string]$Cmd)
    if ([string]::IsNullOrWhiteSpace($Cmd)) { return $false }
    $c = $Cmd.Trim()
    if ($c -match '\|') { return $false }
    $segments = @($c -split '&&|\|\||;' | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' })
    if ($segments.Count -eq 0) { return $false }
    $patterns = @(
        '^(true|:)$', '^exit\s+0$', '^cmd(\.exe)?\s*/c\s+exit\s+0$',
        '^echo\b', '^printf\b', '^Write-Output\b', '^Write-Host\b', '^cd\s+\S+$',
        '^python(\d|\.\d+)?\s+-c\s+["'']?\s*pass\s*["'']?$',
        '^python(\d|\.\d+)?\s+-c\s+["'']?\s*print\(.*\)\s*["'']?$',
        '^python(\d|\.\d+)?\s+-c\s+["'']?\s*(import\s+sys\s*;\s*)?sys\.exit\(0\)\s*["'']?$'
    )
    foreach ($seg in $segments) {
        $hit = $false
        foreach ($pat in $patterns) { if ($seg -match $pat) { $hit = $true; break } }
        if (-not $hit) { return $false }
    }
    return $true
}

# ---------------------------------------------------------------- top-level
$stagesProp = P $profile 'stages'
$stages = @(); if ($null -ne $stagesProp) { $stages = @($stagesProp) }

if ($stages.Count -eq 0) { Add-Fail 'profile' 'stages is empty or missing' }
if ($null -eq (P $profile 'risk_policy')) { Add-Warn 'profile' 'no risk_policy — every task will default to L1' }

# ---------------------------------------------------------------- per-stage
$ALLOWED = @('id', 'goal', 'generates', 'requires', 'verify', 'risk')
$ids = @{}
$generatedBy = @{}

foreach ($s in $stages) {
    $sid = [string](P $s 'id')
    $where = if ($sid) { "stage $sid" } else { 'stage (no id)' }

    if ([string]::IsNullOrWhiteSpace($sid)) { Add-Fail $where 'id is missing'; continue }
    if ($sid -notmatch '^\d+\.\d+(\.\d+)?$') { Add-Fail $where "id '$sid' does not match N.N or N.N.N" }
    if ($ids.ContainsKey($sid)) { Add-Fail $where "duplicate id '$sid'" } else { $ids[$sid] = $s }

    # unknown fields
    foreach ($p in $s.PSObject.Properties) {
        if ($p.Name -in $ALLOWED) { continue }
        $best = $null; $bestD = 99
        foreach ($a in $ALLOWED) {
            $dist = Get-EditDistance -A $p.Name -B $a
            if ($dist -lt $bestD) { $bestD = $dist; $best = $a }
        }
        $hint = if ($bestD -le 3) { " (did you mean '$best'?)" } else { '' }
        Add-Fail $where "unknown field '$($p.Name)'$hint"
    }

    # requires
    $reqProp = P $s 'requires'
    $req = @(); if ($null -ne $reqProp) { $req = @($reqProp) }

    # generates
    $genProp = P $s 'generates'
    $gen = @(); if ($null -ne $genProp) { $gen = @($genProp) }
    if ($gen.Count -eq 0) { Add-Fail $where 'generates is missing or empty (stage can never become done)' }
    foreach ($g in $gen) {
        $gp = [string]$g
        if ([System.IO.Path]::IsPathRooted($gp)) { Add-Fail $where "generates contains an absolute path: $gp" }
        if ($generatedBy.ContainsKey($gp)) {
            Add-Fail $where "file '$gp' is also generated by stage $($generatedBy[$gp]) — ownership must be unique"
        } else { $generatedBy[$gp] = $sid }
    }

    # verify
    $verify = [string](P $s 'verify')
    if ([string]::IsNullOrWhiteSpace($verify)) { Add-Warn $where 'no verify — done cannot be evidenced' }
    elseif (Test-TrivialVerify -Cmd $verify) { Add-Warn $where "verify cannot fail ('$verify') — it will never count as evidence" }

    # risk
    $risk = [string](P $s 'risk')
    if ($risk -and $risk -notin @('L0', 'L1', 'L2')) { Add-Fail $where "risk '$risk' must be L0 / L1 / L2" }
}

# ---------------------------------------------------------------- verify targets
# A verify that names a file nobody produces can never pass, no matter how much
# work gets done - the same class of defect as a dangling foreign key. Planned
# outputs are fine: a stage's verify legitimately cites the file that same stage
# is about to create. Observed in practice: three stages pointed at check-*.ps1
# scripts that were never written, and nobody found out until they blocked work.
foreach ($s in $stages) {
    $sid = [string](P $s 'id')
    $verify = [string](P $s 'verify')
    if ([string]::IsNullOrWhiteSpace($verify)) { continue }
    foreach ($m in [regex]::Matches($verify, '[A-Za-z0-9_\-\.\\/]+\.(?:py|ps1|mjs|psm1)')) {
        $token = $m.Value
        if ($token -match '^\.venv') { continue }
        $norm = ($token -replace '\\', '/')
        if ($generatedBy.ContainsKey($norm) -or $generatedBy.ContainsKey($token)) { continue }
        $abs = if ([System.IO.Path]::IsPathRooted($token)) { $token } else { Join-Path $Root $token }
        if (Test-Path -LiteralPath $abs -PathType Leaf) { continue }
        Add-Fail "stage $sid" "verify depends on '$token': no stage generates it and it does not exist - this verify can never pass"
    }
}

# ---------------------------------------------------------------- verify dependency graph
# `requires` is only HALF the dependency graph. A verify that names a file
# implicitly needs the stage producing it to have run already - and that edge was
# never in the graph, so the cycle check passed while 3.1.2 waited on a script
# that 3.1.3 could not produce until 3.1.2 finished.
#
# Build systems and architecture linters all solve this the same way: force every
# dependency into one graph and check that graph. Bazel reports
# "possible dependency cycle detected" before building anything, because deps are
# declared in BUILD files rather than inferred; ArchUnit's beFreeOfCycles() and
# import-linter's layers contract do it by resolving the full import graph first.
# The lesson is not "check harder", it is "put every edge in the same graph".
$requiresMap = @{}
foreach ($s in $stages) {
    $sidR = [string](P $s 'id')
    if ([string]::IsNullOrWhiteSpace($sidR)) { continue }
    $rp = P $s 'requires'
    $requiresMap[$sidR] = @()
    if ($null -ne $rp) { $requiresMap[$sidR] = @($rp | ForEach-Object { [string]$_ }) }
}

$verifyEdges = @{}
foreach ($s in $stages) {
    $sid = [string](P $s 'id')
    $verify = [string](P $s 'verify')
    if ([string]::IsNullOrWhiteSpace($verify)) { continue }
    foreach ($m in [regex]::Matches($verify, '[A-Za-z0-9_\-\.\\/]+\.(?:py|ps1|mjs|psm1)')) {
        $token = ($m.Value -replace '\\', '/')
        if ($token -match '^\.venv') { continue }
        $owner = $null
        foreach ($key in $generatedBy.Keys) {
            if (($key -replace '\\', '/') -eq $token) { $owner = [string]$generatedBy[$key]; break }
        }
        if ($null -eq $owner -or $owner -eq $sid) { continue }
        if (-not $verifyEdges.ContainsKey($sid)) { $verifyEdges[$sid] = @() }
        if ($verifyEdges[$sid] -notcontains $owner) { $verifyEdges[$sid] += $owner }
    }
}

function Get-DepTargets {
    param([string] $Id, [hashtable] $Req, [hashtable] $Ver)
    $out = @()
    if ($Req.ContainsKey($Id)) { $out += @($Req[$Id] | Where-Object { $_ }) }
    if ($Ver.ContainsKey($Id)) { $out += @($Ver[$Id] | Where-Object { $_ }) }
    return $out
}

foreach ($s in $stages) {
    $sid = [string](P $s 'id')
    if ([string]::IsNullOrWhiteSpace($sid)) { continue }

    # reachable-from-self walk over BOTH edge kinds
    $stack = [System.Collections.Generic.Stack[string]]::new()
    foreach ($d in @(Get-DepTargets -Id $sid -Req $requiresMap -Ver $verifyEdges)) { $stack.Push($d) }
    $seen = @{}
    $cycle = $false
    while ($stack.Count -gt 0) {
        $n = $stack.Pop()
        if ($n -eq $sid) { $cycle = $true; break }
        if ($seen.ContainsKey($n)) { continue }
        $seen[$n] = $true
        foreach ($d in @(Get-DepTargets -Id $n -Req $requiresMap -Ver $verifyEdges)) { $stack.Push($d) }
    }
    if ($cycle) {
        $via = if ($verifyEdges.ContainsKey($sid)) { " (verify depends on " + ($verifyEdges[$sid] -join ', ') + ")" } else { '' }
        Add-Fail "stage $sid" "dependency cycle: this stage reaches itself through requires+verify$via - it can never complete"
    }
}

# ---------------------------------------------------------------- dependency resolution
foreach ($s in $stages) {
    $sid = [string](P $s 'id')
    $reqProp = P $s 'requires'
    $req = @(); if ($null -ne $reqProp) { $req = @($reqProp) }
    foreach ($r in $req) {
        $rid = [string]$r
        if (-not $ids.ContainsKey($rid)) { Add-Fail "stage $sid" "requires unknown stage '$rid'" }
    }
}

# ---------------------------------------------------------------- cycle detection (Kahn)
$graph = @{}
foreach ($s in $stages) {
    $sid = [string](P $s 'id')
    $reqProp = P $s 'requires'
    $req = @(); if ($null -ne $reqProp) { $req = @($reqProp) }
    $graph[$sid] = @($req | ForEach-Object { [string]$_ } | Where-Object { $ids.ContainsKey($_) })
}

$indeg = @{}
foreach ($k in $graph.Keys) { if (-not $indeg.ContainsKey($k)) { $indeg[$k] = 0 } }
foreach ($k in $graph.Keys) { foreach ($dep in $graph[$k]) { $indeg[$k] = $indeg[$k] + 1 } }

$queue = [System.Collections.Generic.Queue[string]]::new()
foreach ($k in $indeg.Keys) { if ($indeg[$k] -eq 0) { $queue.Enqueue($k) } }

$visited = 0; $depth = 0
while ($queue.Count -gt 0) {
    $layer = $queue.Count
    for ($i = 0; $i -lt $layer; $i++) {
        $n = $queue.Dequeue(); $visited++
        foreach ($m in $graph.Keys) {
            if ($graph[$m] -contains $n) {
                $indeg[$m] = $indeg[$m] - 1
                if ($indeg[$m] -eq 0) { $queue.Enqueue($m) }
            }
        }
    }
    $depth++
}
if ($visited -lt $graph.Count) {
    $stuck = @($indeg.Keys | Where-Object { $indeg[$_] -gt 0 })
    Add-Fail 'profile' "dependency cycle among: $($stuck -join ', ')"
}

# ---------------------------------------------------------------- baseline freshness
$baselineState = 'unknown'
if (Test-Path -LiteralPath $localPath -PathType Leaf) {
    try {
        $local = Get-Content -LiteralPath $localPath -Raw -Encoding UTF8 | ConvertFrom-Json
        $bp = P $local 'project_sha256'
        if ($null -ne $bp) {
            $baseline = [string]$bp
            $now = Get-FileSha256Hex -Path $projPath
            if ($baseline -eq '') { $baselineState = 'unset'; Add-Warn 'local.json' 'project_sha256 is empty — T2 contract drift cannot be detected' }
            elseif ($baseline -ne $now) {
                $baselineState = 'stale'
                if ($SyncBaseline -or $Accept) {
                    # AIDE's rule applies: a baseline is only trustworthy if accepting
                    # a change is a deliberate, recorded act ("review the report before
                    # updating; never just overwrite the database"). Rewriting it
                    # silently would let whoever can edit a file also edit the record of
                    # what that file looked like - the exact hole a baseline exists to
                    # close. So the update always writes an event.
                    $oldBaseline = $baseline
                    $local | Add-Member -NotePropertyName project_sha256 -NotePropertyValue $now -Force
                    $local | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $localPath -Encoding utf8
                    $baselineState = 'synced'

                    if (-not [string]::IsNullOrWhiteSpace($Accept)) {
                        # A reviewed contract change: signed on the event itself.
                        # The signature lives here rather than on a separate gate so
                        # one approval cannot silently cover every later change.
                        $cc = [ordered]@{
                            file          = '.harness/project.json'
                            before_sha256 = $oldBaseline
                            after_sha256  = $now
                            why           = $Accept
                            approved_by   = 'human'
                        }
                        $ccJson = ConvertTo-Json -InputObject $cc -Depth 4 -Compress
                        & (Join-Path $PSScriptRoot 'append-event.ps1') -Root $Root -Event contract_change -Actor 'human' -DataJson $ccJson -Quiet | Out-Null
                    }
                    else {
                        # Baseline-only refresh (digest caught up, contract untouched):
                        # an anchor, not a contract change.
                        $anchor = [ordered]@{
                            name  = 'profile_baseline'
                            value = 'verified'
                            from  = $oldBaseline
                            to    = $now
                            why   = 'accepted after review (validate-profile -SyncBaseline)'
                        }
                        $anchorJson = ConvertTo-Json -InputObject $anchor -Depth 4 -Compress
                        & (Join-Path $PSScriptRoot 'append-event.ps1') -Root $Root -Event anchor -Actor 'script' -DataJson $anchorJson -Quiet | Out-Null
                    }
                }
                else { Add-Warn 'local.json' 'baseline differs from current project.json (run with -SyncBaseline after reviewing)' }
            }
            else { $baselineState = 'current' }
        }
        else { Add-Warn 'local.json' 'no project_sha256 field' }
    }
    catch { Add-Warn 'local.json' "unreadable: $($_.Exception.Message)" }
}
else { Add-Warn 'local.json' 'missing' }

# ---------------------------------------------------------------- output
$ok = ($fails.Count -eq 0)
$result = [pscustomobject]@{
    ok            = $ok
    stages        = $stages.Count
    topo_depth    = $depth
    baseline      = $baselineState
    fails         = $fails.ToArray()
    warnings      = $warns.ToArray()
}

if ($Json) { $result | ConvertTo-Json -Depth 6; if ($ok) { exit 0 } else { exit 1 } }

if (-not $Quiet) {
    Write-Host ''
    Write-Host "validate profile: $projPath" -ForegroundColor Cyan
    Write-Host ("  stages       {0}" -f $stages.Count)
    Write-Host ("  topo depth   {0}" -f $depth)
    Write-Host ("  baseline     {0}" -f $baselineState)

    if ($warns.Count -gt 0) {
        Write-Host ''
        Write-Host "  WARN ($($warns.Count))" -ForegroundColor Yellow
        foreach ($w in $warns) { Write-Host ("    ! {0,-14} {1}" -f $w.where, $w.msg) -ForegroundColor Yellow }
    }
    if ($fails.Count -gt 0) {
        Write-Host ''
        Write-Host "  FAIL ($($fails.Count))" -ForegroundColor Red
        foreach ($f in $fails) { Write-Host ("    x {0,-14} {1}" -f $f.where, $f.msg) -ForegroundColor Red }
    }
    Write-Host ''
    if ($ok) { Write-Host '  OK' -ForegroundColor Green } else { Write-Host '  INVALID' -ForegroundColor Red }
    Write-Host ''
}

if ($ok) { exit 0 } else { exit 1 }
